import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const classification = JSON.parse(readFileSync(resolve(process.cwd(), "docs/reports/2026-09-06_I18N_TRANSLATION_DATA_CLASSIFICATION.json"), "utf8"));
const translated = JSON.parse(readFileSync("/private/tmp/wuxuai-translated-static-ui-copy.json", "utf8"));
const second = JSON.parse(readFileSync(resolve(process.cwd(), "docs/reports/2026-09-06_I18N_SECOND_POSITIVE_LIST.json"), "utf8"));
const secondTranslated = JSON.parse(readFileSync("/private/tmp/wuxuai-second-translated-static-ui-copy.json", "utf8"));
const languages = ["de", "en", "fr", "it", "es", "zh", "ko"];
const allowPartial = process.env.ALLOW_PARTIAL_I18N === "1";
const firstMessages = [...classification.approved, ...classification.excluded];
const firstBySource = new Map(firstMessages.map((entry) => [entry.source, entry]));
const secondExternal = second.entries.filter(({ classification: kind }) => kind.endsWith("EXTERNAL_OK"));
const secondBySource = new Map(secondExternal.map((entry) => [entry.source, entry]));
const messages = [
  ...firstMessages,
  ...secondExternal.filter(({ source }) => !firstBySource.has(source)),
].sort((a, b) => a.key.localeCompare(b.key));
const germanDisplayOverride = (source) => source === "Basic" ? "BASIC" : source === "Pro" ? "PRO" : source.replace(/^Premium(?=\b|\s·)/, "PREMIUM");
const sourceToKey = Object.fromEntries(messages.map(({ source, key }) => [source, key]));
const catalogs = Object.fromEntries(languages.map((language) => [
  language,
  Object.fromEntries(messages.map(({ key, source, classification: kind }) => {
    const recovery = secondBySource.get(source);
    const value = language === "de"
      ? germanDisplayOverride(source)
      : recovery
        ? secondTranslated[language]?.[recovery.key] ?? (allowPartial ? germanDisplayOverride(source) : null)
        : kind === "STATIC_UI_COPY"
          ? translated[language]?.[key] ?? (allowPartial ? germanDisplayOverride(source) : null)
          : source;
    return [key, value];
  })),
]));

const missing = languages.flatMap((language) => Object.entries(catalogs[language]).filter(([, value]) => !value).map(([key]) => `${language}:${key}`));
if (missing.length) throw new Error(`MISSING_TRANSLATIONS\n${missing.slice(0, 20).join("\n")}\ncount=${missing.length}`);

const dynamicSources = secondExternal
  .filter(({ source }) => source.includes("${"))
  .map(({ source, placeholders }) => ({ source, key: sourceToKey[source], placeholders }));
const output = `// Generated by scripts/render-i18n-catalog.mjs. Do not edit by hand.\nexport const GENERATED_SOURCE_TO_KEY = Object.freeze(${JSON.stringify(sourceToKey, null, 2)});\n\nexport const GENERATED_DYNAMIC_SOURCES = Object.freeze(${JSON.stringify(dynamicSources, null, 2)});\n\nexport const GENERATED_MESSAGES = Object.freeze(${JSON.stringify(catalogs, null, 2)});\n`;
writeFileSync(resolve(process.cwd(), "src/shared/i18n/messages.generated.mjs"), output);
process.stdout.write(`${JSON.stringify({ keys: messages.length, dynamicSources: dynamicSources.length, languages, missing: missing.length })}\n`);
